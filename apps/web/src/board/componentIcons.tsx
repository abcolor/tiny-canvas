export const FRAME_ICONS: Record<FrameKind, LucideIcon> = {
  phone: Smartphone,
  tablet: Tablet,
  browser: Globe,
  window: AppWindowMac,
};

export function WireframeIcon({ kind, className = 'h-4 w-4' }: { kind: WireframeKind; className?: string }) {
  const Icon = WIREFRAME_ICONS[kind];
  return <Icon className={className} aria-hidden />;
}

export function FrameIcon({ kind, className = 'h-4 w-4' }: { kind: FrameKind; className?: string }) {
  const Icon = FRAME_ICONS[kind];
  return <Icon className={className} aria-hidden />;
}
